// Промты для Gemini (§4, §5, §8, §9 задания).
//
// Три вещи, ради которых промты вынесены в отдельный модуль и покрыты тестами.
//
// §9 — музыки нет нигде. Причём не в виде запрета «не предлагай музыку», а
// буквально: слова о треках и подложках не встречаются в промтах вообще.
// Упоминать то, чего в продукте нет, — значит и тратить токены, и подсказывать
// модели несуществующую возможность. В схеме ответа музыкальных полей тоже
// нет, поэтому предложить их модель технически не может.
//
// §5 — лица только для кадрирования. Модель прямо инструктируется не
// определять личность и не описывать внешность: нужен только прямоугольник,
// чтобы worker удержал объект в кадре 9:16.
//
// §15 — модель выбирает из перечислений. В промте перечислено, что разрешено,
// и сказано, что имена файлов, пути и параметры обработки не нужны.

